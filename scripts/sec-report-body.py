# ═══ 6. Medium Findings ═════════════════════════════════════════════════
h1(story, '6. Medium-Severity Findings')

h2(story, '6.1 M1 - Unbounded JSON-RPC batch processing')
story.append(P('<b>Component:</b> src/lib/zaimem/mcp.ts, handleMcpPost. <b>Risk: medium, denial of service.</b> The '
               'MCP transport accepts JSON-RPC arrays and dispatches every element serially. Without a batch cap, '
               'a single request containing tens of thousands of trivial notifications forced the server to '
               'execute them all within one HTTP request, consuming CPU and memory while blocking the event loop '
               'window. Batch semantics amplify every other per-call cost, including per-tool pack preference '
               'lookups.'))
story.append(P('<b>Remediation.</b> Batches are now capped at 25 requests; larger arrays are rejected with a '
               'JSON-RPC -32600 Invalid Request error before any dispatch. The limit matches the MCP spec '
               'guidance for batch sizing and comfortably covers every observed client pattern. Combined with the '
               'per-token rate limit (H3), the worst-case per-token work per minute is now bounded.'))

h2(story, '6.2 M2 - Token accepted via URL query string')
story.append(P('<b>Component:</b> src/lib/zaimem/auth.ts, extractToken. <b>Risk: medium, credential leakage.</b> '
               'For client convenience the API accepts the token as a query parameter (?token=zm_...) on every '
               'endpoint. Query strings leak into access logs, proxy logs, browser history and the Referer header '
               'of any outbound link clicked from a token-bearing page. The magic prompt generated for agents '
               'additionally documents the query-string form, so real deployments will contain tokens in URLs.'))
story.append(P('<b>Assessment: documented, accepted for now.</b> The header form is the primary and recommended '
               'authentication path; the query form exists because some MCP clients cannot set custom headers. '
               'Tokens are random 192-bit values, rotation is cheap, and the deployment does not emit access logs '
               'to shared storage. Recommendation R6 proposes deprecating the query variant in client docs and '
               'adding a server toggle to reject it once client support allows.'))

h2(story, '6.3 M3 - MCP session registry never evicted')
story.append(P('<b>Component:</b> src/lib/zaimem/mcp.ts, mcpSessions map. <b>Risk: medium, resource exhaustion.</b> '
               'Every JSON-RPC initialize call inserts an entry into an in-memory session map that had no eviction '
               'path and no size cap. Over weeks of uptime with automated agents re-initialising, the map grows '
               'monotonically - a slow memory leak reachable by unauthenticated... rather, by any token holder '
               'issuing repeated initialises, and amplified by the prior absence of rate limiting.'))
story.append(P('<b>Remediation.</b> Registry entries now expire after 24 hours, enforced at insertion time: when '
               'the map exceeds 10,000 entries, stale entries are pruned and the oldest entries are evicted until '
               'under the cap. Session identity remains advisory (authentication is token-based per request), so '
               'eviction has no authorisation impact - verified by the full e2e suite, which re-initialises '
               'sessions extensively.'))

h2(story, '6.4 M4 - Permissive CORS with credential headers')
story.append(P('<b>Component:</b> src/lib/zaimem/auth.ts, CORS_HEADERS. <b>Risk: medium, transport policy.</b> The '
               'MCP endpoint responds with Access-Control-Allow-Origin: * and explicitly allows Authorization and '
               'X-Zaimem-Token headers cross-origin. Any web page can therefore issue credentialed-looking '
               'requests to the API from a victim browser; only the token value itself protects the account. '
               'Because the application uses no cookies and the token must be explicitly attached, the wildcard '
               'does not by itself enable cross-site requests with ambient credentials - but it widens the blast '
               'radius of any separately leaked token (for example via M2) by allowing browser-based abuse from '
               'any origin.'))
story.append(P('<b>Assessment: documented, accepted.</b> Open CORS is a deliberate design choice for an MCP server '
               'that third-party agent runtimes call from arbitrary origins; restricting origins would break the '
               'core product promise. The compensating controls are the token entropy, the new rate limits, and '
               'the batch cap. If a fixed set of partner origins emerges, Allow-Origin should switch to an '
               'allow-list (R7).'))

h2(story, '6.5 M5 - Verbatim internal error messages')
story.append(P('<b>Component:</b> MCP fatal handler, /api/github fail(). <b>Risk: medium, information disclosure.</b> '
               'Uncaught exceptions are returned to clients with err.message embedded in the JSON-RPC error data, '
               'and the GitHub route forwards GhError text plus raw exception strings. Internal messages can reveal '
               'stack-adjacent detail - file paths, upstream API responses, dependency internals - that assists an '
               'attacker in mapping the backend.'))
story.append(P('<b>Assessment: documented.</b> Reviewed call sites only surface GhError messages (already '
               'user-directed) or generic exception text; no secrets, tokens or database contents are included, and '
               'the development server stacks are not part of production responses. The finding is retained as a '
               'hardening item: centralise error serialisation so production responses use stable, low-detail '
               'messages while keeping detail in server logs (R8).'))

